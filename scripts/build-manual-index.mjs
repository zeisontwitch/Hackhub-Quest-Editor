/*
 * Builds the handbook's search index.
 *
 * Walks every page under public/manual/, pulls each heading and its surrounding
 * text, and writes public/manual/search-index.js as a plain assignment to
 * window.MANUAL_INDEX.
 *
 * Why a generated .js file and not a fetched .json: the manual has to open
 * straight off disk (H1), and fetch() is blocked on file://. A <script src> is
 * not, so every page loads the index with a script tag and search works with no
 * server and no connection.
 *
 * Usage: node scripts/build-manual-index.mjs
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("../public/manual/", import.meta.url).pathname;
const OUT = join(ROOT, "search-index.js");

function walk(dir, out = []) {
    if (!existsSync(dir)) return out;
    for (const entry of readdirSync(dir)) {
        const full = join(dir, entry);
        if (statSync(full).isDirectory()) walk(full, out);
        else if (entry.endsWith(".html")) out.push(full);
    }
    return out;
}

/** Strip everything that is not reader-facing prose. */
function proseOf(html) {
    return html
        .replace(/<script[\s\S]*?<\/script>/gi, " ")
        .replace(/<style[\s\S]*?<\/style>/gi, " ")
        .replace(/<nav[\s\S]*?<\/nav>/gi, " ")
        .replace(/<[^>]+>/g, " ")
        .replace(/&amp;/g, "&")
        .replace(/&lt;/g, "<")
        .replace(/&gt;/g, ">")
        .replace(/&quot;/g, '"')
        .replace(/&[a-z]+;/gi, " ")
        .replace(/\s+/g, " ")
        .trim();
}

const entries = [];

for (const file of walk(ROOT)) {
    const html = readFileSync(file, "utf8");
    const relPath = relative(ROOT, file).split("\\").join("/");
    const pageProse = proseOf(html);

    // One entry per heading, carrying the text that follows it. A reader
    // searching a field name or a warning lands on the heading, not the page.
    const headings = [...html.matchAll(/<h([2-4])\s+([^>]*?)>([\s\S]*?)<\/h\1>/g)];

    if (!headings.length) {
        entries.push({ url: relPath, title: pageProse.slice(0, 80), section: relPath, text: pageProse.slice(0, 600) });
        continue;
    }

    for (let i = 0; i < headings.length; i++) {
        const m = headings[i];
        const attrs = m[2];
        const title = proseOf(m[3]);
        const idMatch = /id="([^"]+)"/.exec(attrs);
        // Text between this heading and the next one.
        const from = m.index + m[0].length;
        const to = i + 1 < headings.length ? headings[i + 1].index : html.length;
        const text = proseOf(html.slice(from, to)).slice(0, 700);
        if (!title) continue;
        entries.push({
            url: idMatch ? `${relPath}#${idMatch[1]}` : relPath,
            title,
            section: relPath.replace(/\.html$/, ""),
            text,
        });
    }
}

writeFileSync(
    OUT,
    `/* Generated by scripts/build-manual-index.mjs. Do not edit by hand. */\n` +
        `window.MANUAL_INDEX = ${JSON.stringify(entries)};\n`,
);

console.log(`public/manual/search-index.js — ${entries.length} entries from ${walk(ROOT).length} pages`);
